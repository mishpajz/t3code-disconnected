// Lists outbound URL hosts and tunnel or VPN tool names in the desktop app's
// source, and fails on any (term, file) pair missing from source-baseline.txt.
// This catches calls the egress check never exercises, such as ones behind a
// button or a provider. A listed term is not necessarily a call: review new
// entries, then accept them with --update.
// Usage: node egress-check/source-check.mjs [--update]
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

const root = NodePath.resolve(import.meta.dirname, "..");
const baselinePath = NodePath.join(import.meta.dirname, "source-baseline.txt");

// What ships in the desktop app; see DISCONNECTED.md#scope.
const scope = ["apps/desktop", "apps/server", "apps/web", "packages", "scripts/npm-launcher"];
const textFile = /\.(ts|tsx|js|mjs|cjs|json|ndjson|html|css|sh|ps1|nsh|plist|webmanifest|xml)$/;
// Build scripts, tests and fixtures do not ship in the app.
const skippedFile =
  /(\/scripts\/|\.test\.|\.browser\.|\.stories\.|\/test\/|\/tests\/|\/__tests__\/|\/fixtures?\/|\/testing\/|testkit|TestHarness|\/mocks?\/|^packages\/[^/]*-testing\/)/;

const urlPattern = /\b(?:https?|wss?):\/\/([a-z0-9](?:[a-z0-9.-]*[a-z0-9])?)/gi;
// Names must start a word or identifier, so `runGrok` is not ngrok.
const toolPattern =
  /(?<![a-z])(?:cloudflared|tailscale|headscale|ngrok|localtunnel|devtunnel|zerotier|wireguard|wg-quick|openvpn|netbird|tunnelmole|pinggy|localxpose)/gi;

// Hosts that can never reach a third party: loopback, private ranges, and
// names reserved for documentation and testing (RFC 2606, RFC 6761).
const localHost = (host) =>
  /^(localhost|0\.0\.0\.0|127\.\d+\.\d+\.\d+|10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+|172\.(1[6-9]|2\d|3[01])\.\d+\.\d+)$/.test(
    host,
  ) ||
  /\.(localhost|invalid|test|example|local)$/.test(host) ||
  /(^|\.)example\.(com|net|org)$/.test(host) ||
  !host.includes(".");

const files = NodeChildProcess.execFileSync(
  "git",
  ["ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", ...scope],
  {
    cwd: root,
    encoding: "utf8",
  },
)
  .split("\0")
  .filter((file) => file && textFile.test(file) && !skippedFile.test(file));

const found = new Map();
for (const file of files) {
  const fullPath = NodePath.join(root, file);
  if (!NodeFS.existsSync(fullPath)) continue;
  const text = NodeFS.readFileSync(fullPath, "utf8");
  const terms = new Set();
  for (const [, host] of text.matchAll(urlPattern)) {
    const name = host.toLowerCase();
    if (!localHost(name)) terms.add(name);
  }
  for (const [name] of text.matchAll(toolPattern)) terms.add(name.toLowerCase());
  for (const term of terms) found.set(`${term}\t${file}`, { term, file });
}

const entries = [...found.keys()].sort();
if (process.argv.includes("--update")) {
  NodeFS.writeFileSync(
    baselinePath,
    "# Generated by `node egress-check/source-check.mjs --update`. One reviewed\n" +
      "# term and file per line; see egress-check/README.md.\n" +
      entries.join("\n") +
      "\n",
  );
  console.log(`Wrote ${entries.length} entries to ${NodePath.relative(root, baselinePath)}.`);
  process.exit(0);
}

const baseline = new Set(
  (NodeFS.existsSync(baselinePath) ? NodeFS.readFileSync(baselinePath, "utf8") : "")
    .split("\n")
    .filter((line) => line && !line.startsWith("#")),
);
const added = entries.filter((entry) => !baseline.has(entry));
const removed = [...baseline].filter((entry) => !found.has(entry));

const byTerm = new Map();
for (const { term, file } of found.values()) {
  byTerm.set(term, [...(byTerm.get(term) ?? []), file]);
}
console.log(`Terms in ${files.length} source files (${byTerm.size}):`);
for (const [term, termFiles] of [...byTerm].sort(([a], [b]) => a.localeCompare(b))) {
  console.log(`  ${term}  (${termFiles.length} file${termFiles.length === 1 ? "" : "s"})`);
}
if (removed.length > 0) {
  console.log(`\nNo longer found (${removed.length}); run with --update to drop them:`);
  for (const entry of removed) console.log(`  ${entry.replace("\t", "  ")}`);
}
if (added.length > 0) {
  console.log(`\nNEW (${added.length}):`);
  for (const entry of added) console.log(`  ${entry.replace("\t", "  ")}`);
}
console.log(
  added.length === 0
    ? "\nPASS: nothing outside the baseline."
    : `\nFAIL: ${added.length} new term(s). Check each one; if it is fine, run with --update.`,
);
process.exit(added.length === 0 ? 0 : 1);
